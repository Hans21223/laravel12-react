export const dictionaries = { en, th, ja };
const Context = createContext(null);
export function LocaleProvider({ children, initial }) {
    const [locale, setLocale] = useState(
        () => initial || localStorage.getItem('accord.locale') || 'en',
    );
    const validLocale = dictionaries[locale] ? locale : 'en';
    useEffect(() => {
        localStorage.setItem('accord.locale', validLocale);
        document.documentElement.lang = validLocale;
    }, [validLocale]);
    const intl = { en: 'en-GB', th: 'th-TH', ja: 'ja-JP' }[validLocale];
    const t = (key) => dictionaries[validLocale][key] ?? en[key] ?? key;
    const date = (value, options = {}) =>
        value
            ? new Intl.DateTimeFormat(intl, {
                  day: 'numeric',
                  month: 'short',
                  ...options,
              }).format(
                  new Date(value.length === 10 ? `${value}T12:00:00` : value),
              )
            : t('noDue');
    const number = (value) => new Intl.NumberFormat(intl).format(value || 0);
    const money = (value) =>
        new Intl.NumberFormat(intl, {
            style: 'currency',
            currency: 'THB',
            maximumFractionDigits: 2,
        }).format(value || 0);
    return (
        <Context.Provider
            value={{ locale: validLocale, setLocale, t, date, number, money }}
        >
            {children}
        </Context.Provider>
    );
}
export const useLocale = () => useContext(Context);
